import { createRequire } from 'node:module';
import fs from 'node:fs';
import path from 'node:path';
const root=process.cwd(), out=process.env.DEMO_OUTPUT;
const require=createRequire(path.join(root,'web/package.json'));
const {chromium,expect}=require('@playwright/test');
const browser=await chromium.launch({headless:true});
const context=await browser.newContext({baseURL:'http://127.0.0.1:4175',viewport:{width:1600,height:1200}});
const page=await context.newPage();
const started=Date.now();
const result={provider:'mock',human_experience_test:false,steps:[],page_errors:[],failed_api:[],screenshots:[]};
page.on('pageerror',e=>result.page_errors.push(e.message));
page.on('response',r=>{if(r.url().includes('/api/')&&r.status()>=400)result.failed_api.push({path:new URL(r.url()).pathname,status:r.status()});});
const pass=(name,detail)=>{result.steps.push({name,detail,elapsed_ms:Date.now()-started});console.log('PASS '+name);};
async function shot(name){await page.screenshot({path:path.join(out,name),fullPage:true});result.screenshots.push(name);}
try {
  const username='demo_'+Date.now(),password=process.env.DEMO_PASSWORD;
  const reg=await context.request.post('/api/auth/register',{data:{username,password,nickname:'Mock演示学生'}});
  expect(reg.ok()).toBeTruthy();expect((await reg.json()).code).toBe(0);
  await page.goto('/login');
  await page.getByLabel('用户名').fill(username);
  await page.getByLabel('密码',{exact:true}).fill(password);
  await page.getByRole('button',{name:'进入知错工作台'}).click();
  await expect(page.getByRole('navigation',{name:'功能目录'})).toBeVisible();
  pass('register_and_browser_login','新建专用学生，无固定种子账号');
  const token=await page.evaluate(()=>localStorage.getItem('token'));
  const headers={Authorization:`Bearer ${token}`};
  const get=async url=>{const r=await context.request.get(url,{headers});expect(r.ok()).toBeTruthy();const b=await r.json();expect(b.code).toBe(0);return b.data;};
  await page.goto('/question/create');
  await page.locator('.el-select').first().click();
  await page.getByRole('option',{name:'数学',exact:true}).click();
  const stem='已知二次函数y=x²−6x+5，配方写成(x−3)²+5并判定顶点(3,5)。指出错误并求正确顶点。';
  await page.getByPlaceholder('完整抄录题目条件与问题，便于后续检索和解析').fill(stem);
  await page.getByPlaceholder('记录正确答案、关键步骤或自己的订正').fill('y=(x−3)²−4，顶点(3,−4)，最小值−4；错误是配方遗漏减去9。');
  await page.getByPlaceholder('如：期中试卷 · 第 18 题').fill('2026-09-21 本机Mock流程验证，不是研究样本');
  await page.getByRole('button',{name:'保存并启动解析'}).click();
  await expect(page).toHaveURL(/\/question\/\d+$/);
  const id=Number(page.url().split('/').at(-1));result.question_id=id;
  await expect.poll(async()=>(await get(`/api/ai/analysis/${id}`))?.status,{timeout:45000}).toBe(1);
  await expect(page.getByText('错因分析',{exact:true})).toBeVisible({timeout:20000});
  result.analysis=await get(`/api/ai/analysis/${id}`);
  pass('create_and_mock_analysis',{id,status:result.analysis.status});await shot('01-mock-analysis.png');
  await page.getByRole('tab',{name:'RAG 参考'}).click();
  await expect(page.getByText('本次没有返回参考 ID',{exact:true})).toBeVisible();
  pass('rag_empty_state','隔离新账号无历史参考题，显示空态，不伪造命中');
  await page.getByRole('tab',{name:/相似题/}).click();
  await expect(page.getByText('暂未找到相似题',{exact:true})).toBeVisible();
  pass('similar_empty_state','账号仅有一道题，相似题列表为空');
  await page.getByRole('tab',{name:/AI 变式题/}).click();
  await page.getByRole('button',{name:'生成变式题',exact:true}).click();
  await expect.poll(async()=>(await get(`/api/variant/list?questionId=${id}`)).length,{timeout:30000}).toBe(3);
  await expect(page.locator('.variant-list article')).toHaveCount(3);
  pass('mock_variants',3);await shot('02-mock-variants.png');
  expect((await get(`/api/question/${id}`)).mastery).toBe(0);
  await page.getByRole('button',{name:'开始重做',exact:true}).click();
  const dialog=page.getByRole('dialog',{name:'重做这道错题'});
  await dialog.locator('textarea').fill('配方时应减去9，故顶点为(3,−4)。');
  await dialog.getByText('答对了',{exact:true}).click();
  await dialog.getByRole('button',{name:'提交练习记录'}).click();
  await expect(dialog).toBeHidden();
  result.mastery=(await get(`/api/question/${id}`)).mastery;expect(result.mastery).toBe(15);
  pass('practice_updates_mastery',{before:0,after:15});await shot('03-practice-recorded.png');
  await page.goto('/review');
  await expect(page.getByRole('heading',{name:'复习清单'})).toBeVisible();
  result.today_review=await get('/api/review-plan/today');expect(result.today_review).toHaveLength(0);
  pass('review_page','首个节点明天到期，今日0项；未改日期');await shot('04-review.png');
  await page.goto('/report');
  await expect(page.getByRole('heading',{name:'学情报告',exact:true})).toBeVisible();
  result.weekly_report=await get('/api/report/weekly');
  await expect(page.locator('canvas').first()).toBeVisible();
  pass('report_page',result.weekly_report);await shot('05-report.png');
  expect(result.page_errors).toHaveLength(0);expect(result.failed_api).toHaveLength(0);
  result.passed=true;
}catch(error){result.passed=false;result.error=String(error);await shot('failure.png');process.exitCode=1;}
finally{result.elapsed_ms=Date.now()-started;fs.writeFileSync(path.join(out,'browser-result.json'),JSON.stringify(result,null,2));await browser.close();}
